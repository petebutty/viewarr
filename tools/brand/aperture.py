import math, os, urllib.request
CY, PK = '#00E5FF', '#FF3366'
def P(r, a): return (r * math.cos(a), r * math.sin(a))
def f(x): return f'{x:.2f}'

def aperture_paths(cx, cy, R_ring, ring_w, R_blades, r_hex, rot=-90):
    """Returns (ring_path, blade_paths, hex_path, play_path) in absolute coords."""
    n = 6
    V = [P(r_hex, math.radians(rot + 60 * k)) for k in range(n)]
    # Each hex edge k (V_k -> V_k+1) is extended past V_k+1 until it meets the blade circle: point Pk.
    Pk = []
    for k in range(n):
        ax, ay = V[k]; bx, by = V[(k + 1) % n]
        dx, dy = bx - ax, by - ay; L = math.hypot(dx, dy); dx, dy = dx / L, dy / L
        # solve |B + t d| = R for t > 0
        b = bx * dx + by * dy; c = bx * bx + by * by - R_blades ** 2
        t = -b + math.sqrt(b * b - c)
        Pk.append((bx + t * dx, by + t * dy))
    blades = []
    for k in range(n):
        v0 = V[k]; v1 = V[(k + 1) % n]; p0 = Pk[(k - 1) % n]; p1 = Pk[k]
        pts = lambda p: f'{f(cx + p[0])},{f(cy + p[1])}'
        blades.append(f'M{pts(v0)} L{pts(p0)} A{f(R_blades)},{f(R_blades)} 0 0,1 {pts(p1)} L{pts(v1)} Z')
    hexp = 'M' + ' L'.join(f'{f(cx + x)},{f(cy + y)}' for x, y in V) + ' Z'
    # Ring as a filled annulus (two arcs) so it works as a fill in VectorDrawable.
    ro, ri = R_ring, R_ring - ring_w
    ring = (f'M{f(cx)},{f(cy - ro)} A{f(ro)},{f(ro)} 0 1,1 {f(cx)},{f(cy + ro)} A{f(ro)},{f(ro)} 0 1,1 {f(cx)},{f(cy - ro)} Z '
            f'M{f(cx)},{f(cy - ri)} A{f(ri)},{f(ri)} 0 1,0 {f(cx)},{f(cy + ri)} A{f(ri)},{f(ri)} 0 1,0 {f(cx)},{f(cy - ri)} Z')
    s = r_hex * 0.62  # play triangle
    play = f'M{f(cx - s * 0.45)},{f(cy - s * 0.78)} L{f(cx + s * 0.9)},{f(cy)} L{f(cx - s * 0.45)},{f(cy + s * 0.78)} Z'
    return ring, blades, hexp, play

def svg(size, cx, cy, scale, bg=None, extra=''):
    ring, blades, hexp, play = aperture_paths(cx, cy, 100 * scale, 13 * scale, 80 * scale, 30 * scale)
    g = f'<linearGradient id="g" gradientUnits="userSpaceOnUse" x1="{f(cx - 100 * scale)}" y1="{f(cy - 100 * scale)}" x2="{f(cx + 100 * scale)}" y2="{f(cy + 100 * scale)}"><stop offset="0" stop-color="{CY}"/><stop offset="1" stop-color="{PK}"/></linearGradient>'
    alphas = [1.0, 0.82, 0.92, 0.74, 0.88, 0.78]
    body = ''.join(f'<path d="{b}" fill="url(#g)" fill-opacity="{a}" stroke="#080808" stroke-width="{f(3.2 * scale)}" stroke-linejoin="round"/>' for b, a in zip(blades, alphas))
    w, h = size
    bgr = f'<rect width="{w}" height="{h}" fill="{bg}"/>' if bg else ''
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}"><defs>{g}</defs>{bgr}'
            f'<path d="{ring}" fill="url(#g)" fill-rule="evenodd"/>{body}<path d="{hexp}" fill="#080808"/><path d="{play}" fill="{CY}"/>{extra}</svg>'), (ring, blades, hexp, play, alphas)

def vector_drawable(size, cx, cy, scale):
    ring, blades, hexp, play = aperture_paths(cx, cy, 100 * scale, 13 * scale, 80 * scale, 30 * scale)
    alphas = [1.0, 0.82, 0.92, 0.74, 0.88, 0.78]
    grad = (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{f(cx - 100 * scale)}" android:startY="{f(cy - 100 * scale)}" '
            f'android:endX="{f(cx + 100 * scale)}" android:endY="{f(cy + 100 * scale)}" android:startColor="{CY}" android:endColor="{PK}"/></aapt:attr>')
    out = [f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Viewarr aperture mark (generated by tools/brand/aperture.py) -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n    android:width="108dp" android:height="108dp" android:viewportWidth="{size}" android:viewportHeight="{size}">']
    out.append(f'  <path android:pathData="{ring}" android:fillType="evenOdd">{grad}</path>')
    for b, a in zip(blades, alphas):
        out.append(f'  <path android:pathData="{b}" android:fillAlpha="{a}" android:strokeColor="#080808" android:strokeWidth="{f(3.2 * scale)}" android:strokeLineJoin="round">{grad}</path>')
    out.append(f'  <path android:pathData="{hexp}" android:fillColor="#080808"/>')
    out.append(f'  <path android:pathData="{play}" android:fillColor="{CY}"/>')
    out.append('</vector>\n')
    return '\n'.join(out)

